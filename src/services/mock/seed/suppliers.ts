function certs(supplierKey: string, codes: string[]): Certificate[] {
  return codes.map((code, i) => ({
    id: `${supplierKey}-cert-${i + 1}`,
    ...(CERT_LIBRARY[code] ?? { code, name: code, description: code, issuer: 'Procura Verification' }),
    number: `${code.replace(/\s/g, '')}-VN${2300 + i * 17}`,
    validFrom: '2024-01-09T17:00:00.000Z',
    validTo: '2027-01-08T17:00:00.000Z',
    status: 'verified',
  }));
}

function contact(id: string, name: string, initials: string, title: string, email: string, phone: string): SupplierContact {
  return { id, name, initials, title, email, phone, responsibility: 'Tiếp nhận RFQ & báo giá', notifyNewRfq: true, isPrimary: true, visibleToBuyers: true };
}

